"""Larger development comparison for the two manually reviewed successful pilots."""
import copy
import json
from pathlib import Path
import subprocess
import sys

from dataset_catalog import ROOT,data,read_json,read_rows,sha
from fidelity_alignment import OUT as PARENT
from json_io import write_json
import prefix_prompt_pilot as prefix
import schema_prompt_pilot as queue

OUT=ROOT/'outputs/prefix-alignment-v1'
SIZES={'reliability':64,'bitext':156}
PILOT=prefix.OUT


def prepare():
    results=read_json(PILOT/'results.json')
    for key,n in SIZES.items():
        assert results[key]['formatting_gate_passed'],'Do not expand a failed pilot'
        old=PARENT/key;pilot=PILOT/key;pp=read_json(pilot/'protocol.json');p=copy.deepcopy(read_json(old/'protocol.json'))
        fields=['category','subcategory','difficulty'] if key=='reliability' else ['intent','category','tags']
        conditions=[{'required':{f:c['required'][f] for f in fields},'ranges':{}} for c in p['conditions']]
        assert len(conditions)==n
        p.update(conditions=conditions,prompts=[data(key)['prompt']]*n,
            assistant_prefixes=[prefix.prefix_for(key,c['required']) for c in conditions],
            parent_protocol_sha256=sha(old/'protocol.json'),pilot_protocol_sha256=sha(pilot/'protocol.json'),
            reused_pilot_raw_sha256=sha(pilot/'controlled_generations.jsonl'),reused_pilot_ids=list(range(8)),
            method='Original user prompt plus external leading-label assistant prefix. Remaining fields generated by Gemma. Label frequencies are controller choices, not learned model probabilities.',
            policy='Larger DEVELOPMENT comparison after reviewing two pilot candidates. All first8 pilot outputs reused, no output selection. Fresh remaining IDs8 onward are separately identified. Prior failed controlled arm and raw generic baseline retained. No repair/reroll, new training, test scoring or deployment. Only leading labels controlled; free content, lengths, style and copying still measured.')
        for field in ['prompts','assistant_prefixes','conditions']:assert p[field][:8]==pp[field]
        for field in ['adapter_sha256','batch_seed_start','context','temperature','top_p','top_k']:
            name='baseline_batch_seed_start' if field=='batch_seed_start' else field
            assert p[name]==pp[name]
        d=OUT/key;d.mkdir(parents=True,exist_ok=True)
        if (d/'protocol.json').exists():assert read_json(d/'protocol.json')==p
        else:
            write_json(d/'protocol.json',p)
            for label,source in [('baseline','baseline'),('previous','controlled')]:
                (d/(label+'_generations.jsonl')).write_bytes((old/(source+'_generations.jsonl')).read_bytes())
            (d/'controlled_generations.jsonl').write_bytes((pilot/'controlled_generations.jsonl').read_bytes())
            write_json(d/'baseline_freeze.json',{'protocol_sha256':sha(d/'protocol.json'),'baseline_copy_sha256':sha(d/'baseline_generations.jsonl')})
            write_json(d/'progress.json',{'phase':'prepared','completed':8,'total':n})
    print('220-record comparison frozen;16 reused pilot records,204 fresh attempts.',flush=True)


def report():
    results=prefix.report();verification={}
    for key,n in SIZES.items():
        d=OUT/key;p=read_json(d/'protocol.json');pilot=PILOT/key
        assert sha(pilot/'protocol.json')==p['pilot_protocol_sha256']
        assert sha(pilot/'controlled_generations.jsonl')==p['reused_pilot_raw_sha256']
        raw=read_rows(d/'controlled_generations.jsonl');assert raw[:8]==read_rows(pilot/'controlled_generations.jsonl')
        from dataset_metrics import assess_label
        b,_=assess_label(key,read_rows(d/'baseline_generations.jsonl')[8:],d/'fresh_baseline_records.jsonl')
        c,_=assess_label(key,raw[8:],d/'fresh_controlled_records.jsonl')
        write_json(d/'fresh_subset_metrics.json',{'scope':'Development confirmation after pilot; same fixed source profiles, not an independent final test.', 'ids':list(range(8,n)),'baseline':b,'prefix':c})
        verification[key]={'verified':True,'total':n,'reused_pilot':8,'fresh_attempts':n-8,'raw_sha256':sha(d/'controlled_generations.jsonl'),'protocol_sha256':sha(d/'protocol.json'),'adapter_sha256':p['adapter_sha256']}
    write_json(OUT/'verification.json',verification)
    text=(OUT/'report.md').read_text(encoding='utf-8')
    text+='\n## Pilot reuse and fresh observations\n\nEach source reuses all8 pilot records unchanged. Fresh remaining attempts are identified in each protocol and fresh_subset_metrics.json. Candidate choice used development observations; this is not a fresh final test. No default generator was replaced.\n'
    (OUT/'report.md').write_text(text,encoding='utf-8')
    subprocess.run([str(ROOT/'.venv-analysis/Scripts/python.exe'),str(ROOT/'scripts/run_prefix_alignment.py'),'--plot'],cwd=ROOT,check=True)
    note=('\n## COMPLETE: larger prefix-conditioned development comparison\n\n'
          '220 records (16 reused pilot records,204 new attempts), with all raw attempts,\n'
          'source-fidelity/copying scores and offline plots in `outputs/prefix-alignment-v1/`.\n'
          'Read report.md and fresh_subset_metrics.json before selecting a generator.\n'
          'Supplied label frequencies are external controls; no new weights, test scoring\n'
          'or deployment. InsuranceQA failed the pilot and retained its original method.\n')
    for name in ['decision.md','NEXT_SESSION.md']:
        path=ROOT/name;original=path.read_text(encoding='utf-8')
        if note not in original:
            head,_,tail=original.partition('\n');path.write_text(head+'\n'+note+'\n'+tail,encoding='utf-8')
    return results


if __name__=='__main__':
    if '--prepare' in sys.argv:prepare()
    elif '--plot' in sys.argv:
        import plot_fidelity_alignment as plots
        plots.OUT=OUT;plots.ORDER=list(SIZES);plots.main()
    else:
        prefix.OUT=OUT;prefix.PARENT=PARENT;prefix.SIZES=SIZES
        queue.OUT=OUT;queue.SIZES=SIZES;queue.STATUS=ROOT/'reports/prefix_alignment_status.json';queue.report=report;queue.run()
